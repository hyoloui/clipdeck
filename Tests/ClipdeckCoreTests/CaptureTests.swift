import AppKit
import Foundation
import Testing
@testable import ClipdeckCore

private func rep(_ uti: String, _ text: String) -> Representation {
    Representation(uti: uti, data: Data(text.utf8))
}

private let now = Date(timeIntervalSince1970: 1_000_000)

@Suite struct CaptureTests {
    @Test func decideOrder() {
        var p = CapturePolicy()
        p.pausedUntil = .distantFuture
        p.ignoredBundleIDs = ["com.bad.app"]

        #expect(p.decide(types: [PasteboardTypes.selfMarker, PasteboardTypes.plainText], frontmostBundleID: nil, now: now) == .skip(.selfWrite))
        #expect(p.decide(types: [PasteboardTypes.plainText], frontmostBundleID: "com.bad.app", now: now) == .skip(.paused))

        p.pausedUntil = nil
        #expect(p.decide(types: [PasteboardTypes.concealed], frontmostBundleID: "com.bad.app", now: now) == .skip(.ignoredApp))
        #expect(p.decide(types: [PasteboardTypes.concealed, PasteboardTypes.transient], frontmostBundleID: nil, now: now) == .skip(.concealed))
        #expect(p.decide(types: [PasteboardTypes.transient], frontmostBundleID: nil, now: now) == .skip(.transient))
        #expect(p.decide(types: [PasteboardTypes.autoGenerated], frontmostBundleID: nil, now: now) == .skip(.transient))
        #expect(p.decide(types: [PasteboardTypes.plainText], frontmostBundleID: "com.ok.app", now: now) == .capture)

        p.ignoreConcealed = false
        #expect(p.decide(types: [PasteboardTypes.concealed], frontmostBundleID: nil, now: now) == .capture)
    }

    @Test func pausedExpires() {
        var p = CapturePolicy()
        p.pausedUntil = now.addingTimeInterval(-1)
        #expect(p.decide(types: [PasteboardTypes.plainText], frontmostBundleID: nil, now: now) == .capture)
        p.pausedUntil = now.addingTimeInterval(60)
        #expect(p.decide(types: [PasteboardTypes.plainText], frontmostBundleID: nil, now: now) == .skip(.paused))
    }

    @Test func policyDecodesMissingKeysWithDefaults() throws {
        let p = try JSONDecoder().decode(CapturePolicy.self, from: Data("{}".utf8))
        #expect(p == CapturePolicy())
        let q = try JSONDecoder().decode(CapturePolicy.self, from: Data(#"{"ignoreConcealed":false}"#.utf8))
        #expect(q.ignoreConcealed == false && q.ignoreTransient == true)
    }

    @Test func classifyOrder() {
        #expect(KindClassifier.classify(utis: [PasteboardTypes.plainText, PasteboardTypes.fileURL], plainText: "a.txt") == .file)
        #expect(KindClassifier.classify(utis: [PasteboardTypes.plainText, PasteboardTypes.png], plainText: "x") == .image)
        #expect(KindClassifier.classify(utis: [PasteboardTypes.tiff], plainText: nil) == .image)
        #expect(KindClassifier.classify(utis: [PasteboardTypes.color], plainText: nil) == .color)
        #expect(KindClassifier.classify(utis: [PasteboardTypes.plainText], plainText: "https://a.com") == .link)
        #expect(KindClassifier.classify(utis: [PasteboardTypes.plainText], plainText: "  https://a.com\n") == .link)
        #expect(KindClassifier.classify(utis: [PasteboardTypes.plainText], plainText: "see https://a.com") == .text)
        #expect(KindClassifier.classify(utis: [PasteboardTypes.plainText], plainText: "ftp://a.com") == .text)
        #expect(KindClassifier.classify(utis: [PasteboardTypes.plainText], plainText: "hello") == .text)
        #expect(KindClassifier.classify(utis: ["com.example.private"], plainText: nil) == nil)
    }

    @Test func privateOnlyIsNil() {
        let clip = ClipBuilder.make(representations: [rep("com.example.private", "x")],
                                    sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip == nil)
    }

    @Test func blankTextIsNil() {
        let clip = ClipBuilder.make(representations: [rep(PasteboardTypes.plainText, "  \n\t ")],
                                    sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip == nil)
    }

    @Test func hugeTextPreviewTruncated() throws {
        let big = String(repeating: "가나다 라마바\n", count: 1_000_000)
        let clip = ClipBuilder.make(representations: [rep(PasteboardTypes.plainText, big)],
                                    sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        let c = try #require(clip)
        #expect(c.preview.count <= 300)
        #expect(c.preview.hasPrefix("가나다 라마바 가나다"))
        #expect(c.kind == .text)
        #expect(c.plainText == big)
    }

    @Test func previewCollapsesWhitespace() {
        let clip = ClipBuilder.make(representations: [rep(PasteboardTypes.plainText, "  a \n\n b\t c  ")],
                                    sourceAppBundleID: "com.x", sourceAppName: "X", policy: CapturePolicy())
        #expect(clip?.preview == "a b c")
        #expect(clip?.sourceAppBundleID == "com.x")
        #expect(clip?.sourceAppName == "X")
    }

    @Test func sameTextSameHash() {
        func make(_ t: String, _ extra: [Representation] = []) -> NewClip? {
            ClipBuilder.make(representations: [rep(PasteboardTypes.plainText, t)] + extra,
                             sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        }
        let a = make("hello")
        let b = make("hello", [rep(PasteboardTypes.html, "<b>hello</b>")])
        let c = make("hello!")
        #expect(a?.contentHash == b?.contentHash)
        #expect(a?.contentHash != c?.contentHash)
        #expect(a?.contentHash.count == 64)
        #expect(b?.representations.count == 2)
    }

    @Test func linkKind() {
        let clip = ClipBuilder.make(representations: [rep(PasteboardTypes.plainText, "https://a.com/x")],
                                    sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip?.kind == .link)
        #expect(clip?.plainText == "https://a.com/x")
    }

    @Test func fileKind() {
        let clip = ClipBuilder.make(
            representations: [rep(PasteboardTypes.fileURL, "file:///tmp/a%20b.txt"),
                              rep(PasteboardTypes.fileURL, "file:///tmp/dir/c.png"),
                              rep(PasteboardTypes.plainText, "ignored")],
            sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip?.kind == .file)
        #expect(clip?.preview == "a b.txt, c.png")
        #expect(clip?.plainText?.contains("a b.txt") == true)
    }

    @Test func imageKind() throws {
        let rep0 = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 3, pixelsHigh: 2, bitsPerSample: 8,
                                    samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                    colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        let png = try #require(rep0.representation(using: .png, properties: [:]))
        let clip = ClipBuilder.make(representations: [Representation(uti: PasteboardTypes.png, data: png)],
                                    sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip?.kind == .image)
        #expect(clip?.preview == "이미지 3×2")
        #expect(clip?.plainText == nil)
    }

    @Test func colorKind() throws {
        let color = NSColor(srgbRed: 1, green: 0.5, blue: 0, alpha: 1)
        let data = try NSKeyedArchiver.archivedData(withRootObject: color, requiringSecureCoding: true)
        let clip = ClipBuilder.make(representations: [Representation(uti: PasteboardTypes.color, data: data)],
                                    sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip?.kind == .color)
        #expect(clip?.preview == "#FF8000")
        #expect(clip?.plainText == nil)

        let bad = ClipBuilder.make(representations: [rep(PasteboardTypes.color, "garbage")],
                                   sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(bad?.preview == "색상")
    }

    @Test func mcpHiddenFromPolicy() {
        var p = CapturePolicy()
        p.mcpHiddenBundleIDs = ["com.secret.app"]
        let reps = [rep(PasteboardTypes.plainText, "x")]
        #expect(ClipBuilder.make(representations: reps, sourceAppBundleID: "com.secret.app", sourceAppName: nil, policy: p)?.mcpHidden == true)
        #expect(ClipBuilder.make(representations: reps, sourceAppBundleID: "com.other", sourceAppName: nil, policy: p)?.mcpHidden == false)
        #expect(ClipBuilder.make(representations: reps, sourceAppBundleID: nil, sourceAppName: nil, policy: p)?.mcpHidden == false)
    }

    @Test func fileWithoutDecodableURLIsNil() {
        let clip = ClipBuilder.make(representations: [Representation(uti: PasteboardTypes.fileURL, data: Data([0xFF, 0xFE]))],
                                    sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip == nil)
    }

    @Test func filePreviewTruncated() {
        let reps = (0..<100).map { rep(PasteboardTypes.fileURL, "file:///tmp/long-file-name-\($0).txt") }
        let clip = ClipBuilder.make(representations: reps, sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip?.preview.count == 300)
        #expect(clip?.plainText?.contains("long-file-name-99.txt") == true)
    }

    @Test func tiffOnlyImage() throws {
        let r = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 4, pixelsHigh: 5, bitsPerSample: 8,
                                 samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                 colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        let tiff = try #require(r.representation(using: .tiff, properties: [:]))
        let clip = ClipBuilder.make(representations: [Representation(uti: PasteboardTypes.tiff, data: tiff)],
                                    sourceAppBundleID: nil, sourceAppName: nil, policy: CapturePolicy())
        #expect(clip?.kind == .image)
        #expect(clip?.preview == "이미지 4×5")
    }

    @Test func transientCapturedWhenNotIgnored() {
        var p = CapturePolicy()
        p.ignoreTransient = false
        #expect(p.decide(types: [PasteboardTypes.transient, PasteboardTypes.autoGenerated], frontmostBundleID: nil, now: now) == .capture)
    }
}
