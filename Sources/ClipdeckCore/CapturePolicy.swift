import Foundation

/// 클립보드 표현 타입 식별자 모음
public enum PasteboardTypes {
    public static let selfMarker = "local.hyoloui.clipdeck.self"
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let color = "com.apple.cocoa.pasteboard.color"
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let url = "public.url"
}

public enum SkipReason: Equatable, Sendable {
    case concealed, transient, ignoredApp, paused, selfWrite
    /// `decide`는 내지 않는다. `ClipBuilder.make`가 nil일 때 호출부가 쓴다.
    case empty
}

public enum CaptureDecision: Equatable, Sendable {
    case capture
    case skip(SkipReason)
}

public struct CapturePolicy: Codable, Equatable, Sendable {
    public var ignoreConcealed: Bool
    public var ignoreTransient: Bool
    public var ignoredBundleIDs: Set<String>
    public var mcpHiddenBundleIDs: Set<String>
    public var detectSecrets: Bool
    /// `.distantFuture`이면 무기한 일시정지
    public var pausedUntil: Date?

    public init(ignoreConcealed: Bool = true, ignoreTransient: Bool = true,
                ignoredBundleIDs: Set<String> = [], mcpHiddenBundleIDs: Set<String> = [],
                detectSecrets: Bool = true, pausedUntil: Date? = nil) {
        self.ignoreConcealed = ignoreConcealed
        self.ignoreTransient = ignoreTransient
        self.ignoredBundleIDs = ignoredBundleIDs
        self.mcpHiddenBundleIDs = mcpHiddenBundleIDs
        self.detectSecrets = detectSecrets
        self.pausedUntil = pausedUntil
    }

    // 설정 파일에 없는 키는 기본값으로 채운다(버전 간 호환)
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        self.init(
            ignoreConcealed: try c.decodeIfPresent(Bool.self, forKey: .ignoreConcealed) ?? true,
            ignoreTransient: try c.decodeIfPresent(Bool.self, forKey: .ignoreTransient) ?? true,
            ignoredBundleIDs: try c.decodeIfPresent(Set<String>.self, forKey: .ignoredBundleIDs) ?? [],
            mcpHiddenBundleIDs: try c.decodeIfPresent(Set<String>.self, forKey: .mcpHiddenBundleIDs) ?? [],
            detectSecrets: try c.decodeIfPresent(Bool.self, forKey: .detectSecrets) ?? true,
            pausedUntil: try c.decodeIfPresent(Date.self, forKey: .pausedUntil))
    }

    public func decide(types: [String], frontmostBundleID: String?, now: Date) -> CaptureDecision {
        decide(types: types, recentBundleIDs: frontmostBundleID.map { [$0] } ?? [], now: now)
    }

    /// 판단 순서: selfWrite → paused → ignoredApp → concealed → transient·autoGenerated.
    /// `recentBundleIDs`는 직전 확인 이후 앞에 있던 앱들이다(복사 직후 앱을 바꾼 경우 대비). 하나라도 제외 앱이면 건너뛴다.
    public func decide(types: [String], recentBundleIDs: [String], now: Date) -> CaptureDecision {
        if types.contains(PasteboardTypes.selfMarker) { return .skip(.selfWrite) }
        if let until = pausedUntil, until > now { return .skip(.paused) }
        if recentBundleIDs.contains(where: ignoredBundleIDs.contains) { return .skip(.ignoredApp) }
        if ignoreConcealed, types.contains(PasteboardTypes.concealed) { return .skip(.concealed) }
        if ignoreTransient,
           types.contains(PasteboardTypes.transient) || types.contains(PasteboardTypes.autoGenerated) {
            return .skip(.transient)
        }
        return .capture
    }
}
